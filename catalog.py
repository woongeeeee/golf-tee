def build(progress=None, tokens=None) -> list[dict]:
    """이름검색을 KEYWORDS 로 훑어 유니크 골프장 목록을 만든다."""
    seen: dict[int, dict] = {}
    kws = list(dict.fromkeys(KEYWORDS))
    for i, kw in enumerate(kws):
        try:
            df = ts.search_dataframe(kw, tokens=tokens)
        except Exception:
            df = None
        if df is not None and len(df):
            for _, r in df.iterrows():
                seq = r["seq"]
                if seq is not None and seq not in seen:
                    seen[seq] = {
                        "seq": int(seq),
                        "course": r["course"],
                        "area": r["area"],
                        "address": r["address"],
                        "score": None if pd.isna(r["score"]) else r["score"],
                    }
        if progress:
            progress(i + 1, len(kws), len(seen))
    return sorted(seen.values(), key=lambda x: x["course"])


def save(clubs: list[dict]) -> None:
    try:
        CACHE_FILE.write_text(json.dumps(clubs, ensure_ascii=False, indent=2, default=str), encoding="utf-8")
    except OSError:
        pass


def load() -> list[dict]:
    if CACHE_FILE.exists():
        try:
            return json.loads(CACHE_FILE.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            return []
    return []


def top_region(area: str) -> str:
    """'충청남부 › 아산' → '충청남부'."""
    if not area:
        return ""
    return area.split("›")[0].strip()
